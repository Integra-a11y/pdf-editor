// Generates web/sw.js: precaches every file of the app under a cache named after their content hash, so a new deploy replaces the old cache.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const web = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', 'web');
const skip = new Set(['sw.js']);
const files = [];
(function walk(dir) { for (const e of fs.readdirSync(dir, { withFileTypes: true })) { const p = path.join(dir, e.name); if (e.isDirectory()) walk(p); else if (!skip.has(path.relative(web, p))) files.push(p); } })(web);
files.sort();
const h = crypto.createHash('sha256');
for (const f of files) { h.update(path.relative(web, f)); h.update(fs.readFileSync(f)); }
const version = h.digest('hex').slice(0, 16);
const urls = ['./', ...files.map(f => './' + path.relative(web, f).split(path.sep).join('/'))];
const sw = `// Generated by tools/build-sw.mjs: do not edit by hand.
const CACHE = 'pdf-editor-${version}';
const FILES = ${JSON.stringify(urls, null, 0)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('pdf-editor-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const r = e.request; if (r.method !== 'GET' || new URL(r.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async c => (await c.match(r, { ignoreSearch: true })) || (r.mode === 'navigate' && (await c.match('./'))) || fetch(r)));
});
`;
fs.writeFileSync(path.join(web, 'sw.js'), sw);
console.log(`sw.js: ${urls.length} files, cache ${version}`);
